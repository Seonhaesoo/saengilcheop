export function zodiacOf(m, d) {
  for (const z of ZODIAC) {
    const [fm, fd] = z.from, [tm, td] = z.to;
    if (fm <= tm) {
      if ((m > fm || (m === fm && d >= fd)) && (m < tm || (m === tm && d <= td))) return z;
    } else if ((m > fm || (m === fm && d >= fd)) || (m < tm || (m === tm && d <= td))) return z;
  }
  return ZODIAC[ZODIAC.length - 1];
}
